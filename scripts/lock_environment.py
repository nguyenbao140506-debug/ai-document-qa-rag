"""Capture installed runtime dependency closure for this OS/Python, excluding unrelated packages."""

import importlib.metadata as metadata
import platform
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOTS = [
    "numpy",
    "PyMuPDF",
    "faiss-cpu",
    "sentence-transformers",
    "transformers",
    "huggingface-hub",
    "streamlit",
    "torch",
]


def main():
    environment = {**default_environment(), "extra": ""}
    pending = ROOTS.copy()
    packages = {}
    while pending:
        name = canonicalize_name(pending.pop())
        if name in packages:
            continue
        distribution = metadata.distribution(name)
        packages[name] = distribution.version
        for value in distribution.requires or []:
            dependency = Requirement(value)
            if dependency.marker is None or dependency.marker.evaluate(environment):
                pending.append(dependency.name)
    header = (
        f"# Tested runtime dependency closure: {platform.system()}, Python {platform.python_version()}\n"
        "# Generated by scripts/lock_environment.py; optional packages and dev tools are excluded.\n"
    )
    lines = [f"{name}=={version}" for name, version in sorted(packages.items())]
    destination = Path(__file__).resolve().parents[1] / "requirements-lock.windows-py313.txt"
    destination.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"Captured {len(packages)} runtime dependencies in {destination.name}")


if __name__ == "__main__":
    main()
